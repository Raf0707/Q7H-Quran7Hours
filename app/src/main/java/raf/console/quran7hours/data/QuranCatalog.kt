    enum class Segment(val title: String) {
        SURAH("Суры"), PAGE("Страницы"), JUZ("Джузы"), HIZB("Хизбы"), MANZIL("Манзили")
    }
    fun startPages(segment: Segment): IntArray = when (segment) {
        Segment.SURAH -> surahPages
        Segment.PAGE -> IntArray(TOTAL_PAGES) { it + 1 }
        Segment.JUZ -> juzPages
        Segment.HIZB -> hizbPages
        Segment.MANZIL -> manzilPages
    }
    fun segmentForPage(segment: Segment, page: Int): Int {
        val values = startPages(segment)
        // Same-page multiple surah starts are handled with a last-start <= current-page rule.
        return max(1, values.indexOfLast { it <= page } + 1)
    }
    fun label(segment: Segment, number: Int): String = when (segment) {
        Segment.SURAH -> "Сура $number · ${surahNames.getOrNull(number - 1) ?: ""}"
        Segment.PAGE -> "Страница $number"
        Segment.JUZ -> "Джуз $number"
        Segment.HIZB -> "Хизб $number"
        Segment.MANZIL -> "Манзиль $number"
    }
    fun isValidAyah(surah: Int, ayah: Int): Boolean = surah in 1..114 && ayah in 1..ayahCounts[surah - 1]
    fun nextAyah(surah: Int, ayah: Int): Pair<Int, Int>? = when {
        !isValidAyah(surah, ayah) -> null
        ayah < ayahCounts[surah - 1] -> surah to (ayah + 1)
        surah < 114 -> (surah + 1) to 1
        else -> null
    }
